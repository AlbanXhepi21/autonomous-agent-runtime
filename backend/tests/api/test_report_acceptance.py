# --------------------------------------------------------------------- PDF


def test_the_pdf_embeds_the_chart_as_an_image(published) -> None:
    reader = PdfReader(str(published["pdf"]))

    images = sum(len(page.images) for page in reader.pages)
    assert images >= 1, "the stacked bar was not embedded"


def test_the_pdf_numbers_every_page_and_repeats_its_header(published) -> None:
    reader = PdfReader(str(published["pdf"]))

    assert len(reader.pages) > 1
    for number, page in enumerate(reader.pages, start=1):
        text = " ".join(page.extract_text().split())
        assert f"Page {number}" in text
        assert "Monthly Business Review" in text
        assert RUN_ID in text


def test_the_page_break_puts_the_appendix_on_its_own_page(published) -> None:
    pages = [" ".join(page.extract_text().split()) for page in PdfReader(str(published["pdf"])).pages]

    appendix = next(index for index, text in enumerate(pages) if "Evidence Appendix" in text)
    limitations = next(index for index, text in enumerate(pages) if "Limitations" in text)
    assert appendix > limitations, "the appendix did not start after the limitations"


