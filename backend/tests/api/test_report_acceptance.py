# ------------------------------------------------------------- artifact record


@pytest.mark.parametrize("fmt", ["pdf", "docx"])
def test_the_record_states_the_bytes_that_were_written(published, fmt: str) -> None:
    artifact = published["artifacts"][fmt]
    path = published[fmt]

    data = path.read_bytes()
    assert artifact.size == len(data)
    assert artifact.sha256 == sha256(data).hexdigest()
    # And the key is provider-independent, so it resolves elsewhere.
    assert artifact.relative_path == f"artifacts/{RUN_ID}/{artifact.id}/{artifact.name}"
    assert not Path(artifact.relative_path).is_absolute()


def test_publishing_this_run_reaches_no_model() -> None:
    """Asserting no call was made would pass trivially; the graph is the proof."""

    import ast
    from collections import deque

    from tests.support import BACKEND_ROOT

    def path_of(name: str):
        base = BACKEND_ROOT / name.replace(".", "/")
        for candidate in (base.with_suffix(".py"), base / "__init__.py"):
            if candidate.is_file():
                return candidate
        return None

    seen, queue = set(), deque(["app.orchestration.publishing"])
    while queue:
        name = queue.popleft()
        path = path_of(name)
        if name in seen or path is None:
            continue
        seen.add(name)
        for node in ast.walk(ast.parse(path.read_text())):
            if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("app."):
                queue.append(node.module)
            elif isinstance(node, ast.Import):
                queue.extend(alias.name for alias in node.names if alias.name.startswith("app."))

    assert not [name for name in seen if name.startswith("app.llm")]
